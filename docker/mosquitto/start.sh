#!/bin/sh
# Starts the RuView bus: mosquitto.conf plus a bridge to Home Assistant's
# broker, built from the environment:
#   MQTT_HOST, MQTT_PORT   Home Assistant's broker; no bridge if MQTT_HOST is empty
#   MQTT_USER, MQTT_PASS   its login (the one the services used before the bus)
#   MQTT_PREFIX            RuView topics (ruview)
#   HA_DISCOVERY_PREFIX    Home Assistant discovery topics (homeassistant)
#
# Only the topics listed below cross the bridge. Everything else stays on the
# NAS, notably <prefix>/state (up to 10 messages per second), node, bridge and
# recorder health, and the watchdog metrics.
set -eu

fail() {
    echo "start.sh: $*" >&2
    exit 1
}

host="${MQTT_HOST:-}"
port="${MQTT_PORT:-1883}"
user="${MQTT_USER:-}"
pass="${MQTT_PASS:-}"
p="${MQTT_PREFIX:-ruview}"
ha="${HA_DISCOVERY_PREFIX:-homeassistant}"

# The generated file holds the password: readable by the broker's user only.
conf=/tmp/mosquitto.conf
umask 077
cat /mosquitto/config/mosquitto.conf > "$conf"

if [ -z "$host" ]; then
    echo "start.sh: MQTT_HOST is empty, running without the Home Assistant bridge"
    exec /usr/sbin/mosquitto -c "$conf"
fi

# The values are written into the config file: refuse anything that could
# start a new line or change a topic pattern.
nl='
'
cr="$(printf '\r')"
case "$host" in
    *[!A-Za-z0-9.-]*) fail "MQTT_HOST must be a host name or an IPv4 address" ;;
esac
case "$port" in
    '' | *[!0-9]* | ??????*) fail "MQTT_PORT must be a port number" ;;
esac
[ "$port" -ge 1 ] && [ "$port" -le 65535 ] || fail "MQTT_PORT must be a port number"
for prefix in "$p" "$ha"; do
    case "$prefix" in
        '' | /* | */ | *//* | *[!A-Za-z0-9_/-]*) fail "invalid topic prefix '$prefix'" ;;
    esac
done
for value in "$user" "$pass"; do
    case "$value" in
        *"$nl"* | *"$cr"*) fail "MQTT_USER and MQTT_PASS must be a single line" ;;
        [[:space:]]* | *[[:space:]]) fail "MQTT_USER and MQTT_PASS must not start or end with a space" ;;
    esac
done

cat >> "$conf" <<EOF

# Bridge to Home Assistant's broker (generated by start.sh)
connection ha
address $host:$port
remote_clientid ruview-nas-bus
keepalive_interval 30
# Each connection starts clean, so a topic removed below stops crossing at
# the next start. Retained messages are re-sent on every connect, which
# restores the discovery configs if Home Assistant's broker lost them.
cleansession true
try_private true
# 1 while connected, 0 when not, retained on both brokers: Home Assistant's
# broker publishes the 0 itself if the connection breaks. The watchdog shows
# it in Home Assistant as "NAS Link".
notifications true
notification_topic $p/bus/ha_connected
EOF
if [ -n "$user" ]; then
    printf 'remote_username %s\nremote_password %s\n' "$user" "$pass" >> "$conf"
fi
cat >> "$conf" <<EOF
# NAS -> Home Assistant: the entities' discovery configs, states and
# availability, and the results of keep requests.
topic $ha/# out 1
topic $p/availability out 1
topic $p/person/# out 1
topic $p/nodes/# out 0
topic $p/event out 1
topic $p/watchdog/state out 1
topic $p/watchdog/availability out 1
topic $p/recorder/keep/result out 1
# Home Assistant -> NAS: the label buttons.
topic $p/annotation in 1
topic $p/recorder/keep in 1
EOF

echo "start.sh: bridging to Home Assistant's broker at $host:$port${user:+ as $user}"
exec /usr/sbin/mosquitto -c "$conf"
